import { z } from "zod";

/**
 * harness.yaml — the single declarative input.
 * Every emitted artifact must trace back to a field here or to a selected pack.
 */

export const TARGETS = ["devin", "claude", "cursor", "windsurf", "copilot", "codex"] as const;
export type Target = (typeof TARGETS)[number];

export const SLOTS = ["stack", "architecture", "style", "safety", "workflow"] as const;
export type Slot = (typeof SLOTS)[number];

export const layerSchema = z.object({
  /** Layer name, also used as the import-boundary identity. */
  name: z.string().regex(/^[a-z][a-z0-9_-]*$/),
  /** Glob prefixes this layer owns, e.g. ["src/domain/**"]. */
  paths: z.array(z.string().min(1)).min(1),
  /** Layers this one may import from. Omitting = may import nothing. */
  may_import: z.array(z.string()).default([]),
});

/**
 * Brownfield ratchet entry: one file (or glob) that may violate its layer's
 * may_import for a fixed set of target layers. Shrink-only — delete the entry
 * when the file is fixed, never grow it.
 */
export const exceptionSchema = z.object({
  /** Repo-relative path or glob, e.g. "apps/backend/src/lib/adfWire.ts". */
  file: z.string().min(1),
  /** Layer names this file may import beyond its own layer's may_import. */
  allow: z.array(z.string()).min(1),
});

const projectSchema = z.object({
  name: z.string().optional(),
  /** Free-text design intent; used for catalog matching only, never copied to output. */
  intent: z.string().default(""),
});

const stackSchema = z.object({
  language: z.string().default("typescript"),
  package_manager: z.string().default("pnpm"),
  /** Library/framework keys matched against pack.stack_keys, e.g. ["react","prisma"]. */
  frameworks: z.array(z.string().toLowerCase()).default([]),
});

const architectureSchema = z.object({
  /** Named pattern for catalog matching (e.g. "layered", "hexagonal"). Informational unless layers are set. */
  style: z.string().default(""),
  /** Ordered inner → outer. When non-empty, boundary enforcement is generated. */
  layers: z.array(layerSchema).default([]),
  /** Ratchet: per-file carve-outs from layer rules. Generated by `keel ratchet`; shrink-only. */
  exceptions: z.array(exceptionSchema).default([]),
});

const styleSchema = z.object({
  paradigm: z.enum(["fp", "oop", "hybrid"]).default("hybrid"),
  max_function_lines: z.number().int().nonnegative().default(0), // 0 = don't enforce
  max_nesting: z.number().int().nonnegative().default(0),
  comments: z.enum(["minimal", "jsdoc-public", "normal"]).default("minimal"),
  /** Free-form principle keys matched to packs (e.g. ["solid","atomic-design","tdd"]). */
  principles: z.array(z.string().toLowerCase()).default([]),
});

const safetySchema = z.object({
  profile: z.enum(["minimal", "standard", "strict"]).default("standard"),
  extra_allow: z.array(z.string()).default([]),
  extra_ask: z.array(z.string()).default([]),
  extra_deny: z.array(z.string()).default([]),
});

const autonomySchema = z.object({
  mode: z.enum(["guided", "autonomous-verified", "strict-gated"]).default("autonomous-verified"),
  /** Shell command the agent must run before ending a turn. */
  verify: z.string().default(""),
  /** Cheaper command for the per-turn Stop gate (`verify.mjs --fast`); falls back to verify when unset. */
  verify_fast: z.string().default(""),
  verify_timeout_sec: z.number().int().positive().default(180),
  /** Emit a Stop hook that runs verify and blocks premature completion. */
  stop_hook: z.boolean().default(true),
  /** Re-inject invariants after context compaction. */
  post_compaction: z.boolean().default(true),
  /** Emit a CI workflow gating PRs on lockfile drift + the verify gate. */
  ci: z.enum(["none", "github"]).default("none"),
});

const budgetSchema = z.object({
  /** Hard cap on generated always-on prose (AGENTS.md managed block). */
  always_on_tokens: z.number().int().positive().default(1000),
  max_skills: z.number().int().nonnegative().default(5),
});

const packsSchema = z.object({
  /** Force-include pack ids (skip selection scoring). */
  include: z.array(z.string()).default([]),
  exclude: z.array(z.string()).default([]),
  /** Extra pack directories, repo-relative — loaded after the bundled catalog; later dirs override by id. */
  dirs: z.array(z.string()).default([]),
});

export const specSchema = z.object({
  version: z.literal(1),

  project: projectSchema.default({}),

  /** Which agent configs to emit. AGENTS.md is always emitted (cross-tool). */
  targets: z.array(z.enum(TARGETS)).default(["devin"]),

  stack: stackSchema.default({}),
  architecture: architectureSchema.default({}),
  style: styleSchema.default({}),
  safety: safetySchema.default({}),
  autonomy: autonomySchema.default({}),
  budget: budgetSchema.default({}),
  packs: packsSchema.default({}),
});

export type HarnessSpec = z.infer<typeof specSchema>;
export type Layer = z.infer<typeof layerSchema>;
export type BoundaryException = z.infer<typeof exceptionSchema>;

/**
 * harness.local.yaml — personal, gitignored overrides. Same shape as the spec
 * but every field optional and NO defaults applied (a field absent here must
 * not inherit a schema default, or it would clobber the committed value).
 */
export const localSpecSchema = z
  .object({
    version: z.literal(1).optional(),
    project: projectSchema.partial().optional(),
    targets: z.array(z.enum(TARGETS)).optional(),
    stack: stackSchema.partial().optional(),
    architecture: architectureSchema.partial().optional(),
    style: styleSchema.partial().optional(),
    safety: safetySchema.partial().optional(),
    autonomy: autonomySchema.partial().optional(),
    budget: budgetSchema.partial().optional(),
    packs: packsSchema.partial().optional(),
  })
  .strict();
export type LocalSpec = z.infer<typeof localSpecSchema>;

/** The user's cross-project defaults — same style section, stored in the devin user dir. */
export const tasteSchema = z.object({
  paradigm: z.enum(["fp", "oop", "hybrid"]).optional(),
  max_function_lines: z.number().int().nonnegative().optional(),
  max_nesting: z.number().int().nonnegative().optional(),
  comments: z.enum(["minimal", "jsdoc-public", "normal"]).optional(),
  principles: z.array(z.string().toLowerCase()).optional(),
  safety: z
    .object({
      profile: z.enum(["minimal", "standard", "strict"]).optional(),
      extra_allow: z.array(z.string()).optional(),
      extra_ask: z.array(z.string()).optional(),
      extra_deny: z.array(z.string()).optional(),
    })
    .optional(),
  autonomy: z
    .object({
      mode: z.enum(["guided", "autonomous-verified", "strict-gated"]).optional(),
      verify: z.string().optional(),
      verify_fast: z.string().optional(),
      verify_timeout_sec: z.number().int().positive().optional(),
      stop_hook: z.boolean().optional(),
      post_compaction: z.boolean().optional(),
    })
    .optional(),
  budget: z
    .object({
      always_on_tokens: z.number().int().positive().optional(),
      max_skills: z.number().int().nonnegative().optional(),
    })
    .optional(),
});
export type TasteProfile = z.infer<typeof tasteSchema>;
